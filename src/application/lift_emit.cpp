constexpr std::string_view Header = "lifted.h";

std::string ShardName(std::size_t index) {
    return std::format("shard_{:04}.cpp", index);
}

std::string RegisterFunctionName(std::size_t index) {
    return std::format("register_shard_{:04}", index);
}

std::string HeaderText(const std::vector<std::string>& declarations) {
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#pragma once\n\n"
                       "#include \"domain/lift/runtime.h\"\n\n"
                       "namespace lifted {\n\n"
                       "namespace runtime = hexlith::domain::lift::runtime;\n"
                       "namespace arm = hexlith::domain::arm;\n"
                       "namespace memory = hexlith::domain::memory;\n"
                       "namespace primitives = hexlith::domain::arm::primitives;\n\n";
    for (const std::string& declaration : declarations) {
        text += declaration;
        text += '\n';
    }
    text += "\n}  // namespace lifted\n";
    return text;
}

std::string RegistryText(std::size_t shards, const LiftEmitReport& report) {
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#include \"lifted.h\"\n\n"
                       "namespace lifted {\n";
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("void {}(runtime::EntryTable& table);\n", RegisterFunctionName(index));
    }
    text += std::format(
        "\n}}  // namespace lifted\n\n"
        "extern \"C\" {{\n\n"
        "__attribute__((visibility(\"default\"))) const char* {}() {{\n"
        "    return \"lifter={} code={} functions={}\";\n"
        "}}\n\n"
        "__attribute__((visibility(\"default\"))) void {}(void* table) {{\n"
        "    auto& entries = *static_cast<hexlith::domain::lift::runtime::EntryTable*>(table);\n",
        ManifestSymbol,
        LifterVersion,
        report.code_hash,
        report.functions,
        RegisterSymbol);
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("    lifted::{}(entries);\n", RegisterFunctionName(index));
    }
    text += "}\n\n}  // extern \"C\"\n";
    return text;
}

std::string CMakeText(std::size_t shards) {
    std::string text =
        "# Generated by hexlith-lift. Build with scripts/build-lifted.sh.\n"
        "cmake_minimum_required(VERSION 3.25)\n"
        "project(hexlith_lifted CXX)\n\n"
        "if(NOT HEXLITH_SOURCE_DIR)\n"
        "    message(FATAL_ERROR \"Pass -DHEXLITH_SOURCE_DIR=<the Hexlith checkout>\")\n"
        "endif()\n\n"
        "set(CMAKE_CXX_STANDARD 20)\n"
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n"
        "set(CMAKE_POSITION_INDEPENDENT_CODE ON)\n\n"
        "add_library(hexlith_lifted SHARED\n    registry.cpp\n";
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("    {}\n", ShardName(index));
    }
    text +=
        ")\n\n"
        "target_include_directories(hexlith_lifted PRIVATE ${HEXLITH_SOURCE_DIR}/src)\n\n"
        "# The same floating point rules as the interpreter (ADR 0010): no fused\n"
        "# multiply-add. Warnings are off because the code is long, repetitive and\n"
        "# written by a program.\n"
        "target_compile_options(hexlith_lifted PRIVATE -O1 -ffp-contract=off -fvisibility=hidden -w)\n";
    return text;
}

// Adds what was written to the report's count of the C++ produced.
void CountWritten(LiftEmitReport& report, std::string_view text) {
    report.source_bytes += text.size();
    report.source_lines += static_cast<std::size_t>(std::ranges::count(text, '\n'));
}

// Gathers functions into shards of about the same number of instructions, and
// writes each shard once it holds enough.
class ShardWriter {
public:
    ShardWriter(ports::BlobSink& sink, LiftEmitReport& report, std::size_t instructions_per_shard)
        : sink_(&sink), report_(&report), instructions_per_shard_(instructions_per_shard) {}

    core::Status
    Add(std::string_view function, std::string_view registration, std::size_t instructions) {
        text_ += function;
        text_ += '\n';
        registration_ += registration;
        instructions_ += instructions;
        if (instructions_ >= instructions_per_shard_) {
            return Close();
        }
        return {};
    }

    // Writes the shard being gathered, if it holds anything.
    core::Status Close() {
        if (text_.empty()) {
            return {};
        }
        const std::string text =
            std::format("// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                        "#include \"{}\"\n\nnamespace lifted {{\n\n{}\n"
                        "void {}(runtime::EntryTable& table) {{\n{}}}\n\n}}  // namespace lifted\n",
                        Header,
                        text_,
                        RegisterFunctionName(written_),
                        registration_);
        CountWritten(*report_, text);
        const core::Status written = sink_->WriteText(ShardName(written_), text);
        text_.clear();
        registration_.clear();
        instructions_ = 0;
        ++written_;
        return written;
    }

    [[nodiscard]] std::size_t Written() const {
        return written_;
    }

private:
    ports::BlobSink* sink_;
    LiftEmitReport* report_;
    std::size_t instructions_per_shard_;
    std::string text_;
    std::string registration_;
    std::size_t instructions_ = 0;
    std::size_t written_ = 0;
};

struct SortedTables {
    std::vector<analysis::FunctionRange> functions;
    std::vector<analysis::Region> regions;
};

// The function and region tables, each in the order of its addresses.
core::Result<SortedTables> ReadSortedTables(const LiftEmitRequest& request) {
    core::Result<std::vector<analysis::FunctionRange>> functions =
        analysis::ParseFunctions(request.functions);
    if (!functions) {
        return functions.Failure().WithContext("functions.txt");
    }
    core::Result<std::vector<analysis::Region>> regions = analysis::ParseRegions(request.regions);
    if (!regions) {
        return regions.Failure().WithContext("regions.txt");
    }
    std::ranges::sort(
        regions.Value(), {}, [](const analysis::Region& region) { return region.address; });
    std::ranges::sort(functions.Value(), {}, [](const analysis::FunctionRange& function) {
        return function.address;
    });
    return SortedTables{.functions = std::move(functions.Value()),
                        .regions = std::move(regions.Value())};
}

// The lines that add each address the function can be entered at to the table
// of entries.
std::string Registration(const lift::EmittedFunction& emitted,
                         domain::arm::InstructionSet set,
                         std::string_view name) {
    std::string text;
    for (const std::uint32_t entry : emitted.entries) {
        text += std::format("    table.Add(0x{:08X}U, {}, &{});\n",
                            entry,
                            set == domain::arm::InstructionSet::Thumb ? "true" : "false",
                            name);
    }
    return text;
}

// The header every shard includes, the registry and the CMake project that
// builds them.
core::Status WriteProjectFiles(const std::vector<std::string>& declarations,
                               LiftEmitReport& report,
                               ports::BlobSink& sink) {
    const std::string header = HeaderText(declarations);
    const std::string registry = RegistryText(report.shards, report);
    const std::string cmake = CMakeText(report.shards);
    for (const auto& [path, text] :
         {std::pair<std::string_view, const std::string&>{Header, header},
          {"registry.cpp", registry},
          {"CMakeLists.txt", cmake}}) {
        if (const core::Status written = sink.WriteText(path, text); !written) {
            return written;
        }
        CountWritten(report, text);
    }
    return {};
}

