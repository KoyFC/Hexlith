constexpr std::string_view Header = "lifted.h";

std::string ShardName(std::size_t index) {
    return std::format("shard_{:04}.cpp", index);
}

std::string RegisterFunctionName(std::size_t index) {
    return std::format("register_shard_{:04}", index);
}

std::string HeaderText(const std::vector<std::string>& declarations) {
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#pragma once\n\n"
                       "#include \"domain/lift/runtime.h\"\n\n"
                       "namespace lifted {\n\n"
                       "namespace runtime = hexlith::domain::lift::runtime;\n"
                       "namespace arm = hexlith::domain::arm;\n"
                       "namespace memory = hexlith::domain::memory;\n"
                       "namespace primitives = hexlith::domain::arm::primitives;\n\n";
    for (const std::string& declaration : declarations) {
        text += declaration;
        text += '\n';
    }
    text += "\n}  // namespace lifted\n";
    return text;
}

std::string RegistryText(std::size_t shards, const LiftEmitReport& report) {
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#include \"lifted.h\"\n\n"
                       "namespace lifted {\n";
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("void {}(runtime::EntryTable& table);\n", RegisterFunctionName(index));
    }
    text += std::format(
        "\n}}  // namespace lifted\n\n"
        "extern \"C\" {{\n\n"
        "__attribute__((visibility(\"default\"))) const char* {}() {{\n"
        "    return \"lifter={} code={} functions={}\";\n"
        "}}\n\n"
        "__attribute__((visibility(\"default\"))) void {}(void* table) {{\n"
        "    auto& entries = *static_cast<hexlith::domain::lift::runtime::EntryTable*>(table);\n",
        ManifestSymbol,
        LifterVersion,
        report.code_hash,
        report.functions,
        RegisterSymbol);
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("    lifted::{}(entries);\n", RegisterFunctionName(index));
    }
    text += "}\n\n}  // extern \"C\"\n";
    return text;
}

std::string CMakeText(std::size_t shards) {
    std::string text =
        "# Generated by hexlith-lift. Build with scripts/build-lifted.sh.\n"
        "cmake_minimum_required(VERSION 3.25)\n"
        "project(hexlith_lifted CXX)\n\n"
        "if(NOT HEXLITH_SOURCE_DIR)\n"
        "    message(FATAL_ERROR \"Pass -DHEXLITH_SOURCE_DIR=<the Hexlith checkout>\")\n"
        "endif()\n\n"
        "set(CMAKE_CXX_STANDARD 20)\n"
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n"
        "set(CMAKE_POSITION_INDEPENDENT_CODE ON)\n\n"
        "add_library(hexlith_lifted SHARED\n    registry.cpp\n";
    for (std::size_t index = 0; index < shards; ++index) {
        text += std::format("    {}\n", ShardName(index));
    }
    text +=
        ")\n\n"
        "target_include_directories(hexlith_lifted PRIVATE ${HEXLITH_SOURCE_DIR}/src)\n\n"
        "# The same floating point rules as the interpreter (ADR 0010): no fused\n"
        "# multiply-add. Warnings are off because the code is long, repetitive and\n"
        "# written by a program.\n"
        "target_compile_options(hexlith_lifted PRIVATE -O1 -ffp-contract=off -fvisibility=hidden -w)\n";
    return text;
}

