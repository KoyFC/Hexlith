constexpr std::size_t WordSize = 4;

bool IsIdentifier(std::string_view name) {
    return !name.empty() && std::isdigit(static_cast<unsigned char>(name.front())) == 0 &&
           std::ranges::all_of(name, [](char each) {
               return std::isalnum(static_cast<unsigned char>(each)) != 0 || each == '_';
           });
}

// The words of a module's code segments that a relocation writes, as the file
// offsets of the aligned words they touch. The file holds these as they were
// before the loader patched them, which is not what the processor runs.
std::unordered_set<std::uint32_t> RelocatedCodeWords(const domain::linker::CroModule& module) {
    std::unordered_set<std::uint32_t> words;
    const auto note = [&](const domain::ctr::CroSegmentTag& target) {
        const std::size_t index = target.SegmentIndex();
        if (index >= module.header.segments.size()) {
            return;
        }
        const domain::ctr::CroSegment& segment = module.header.segments.at(index);
        if (!segment.type_known || segment.type != domain::ctr::CroSegmentType::Code) {
            return;
        }
        const auto position = static_cast<std::uint32_t>(segment.offset + target.OffsetInSegment());
        words.insert(position & ~static_cast<std::uint32_t>(WordSize - 1));
        if (position % WordSize != 0) {
            words.insert((position & ~static_cast<std::uint32_t>(WordSize - 1)) + WordSize);
        }
    };
    for (const auto& relocation : module.tables.internal_relocations) {
        note(relocation.target);
    }
    for (const auto& relocation : module.tables.external_relocations) {
        note(relocation.target);
    }
    for (const auto& relocation : module.tables.static_relocations) {
        note(relocation.target);
    }
    return words;
}

// The code segment the lifter reads: the first one with anything in it.
const domain::ctr::CroSegment* CodeSegmentOf(const domain::linker::CroModule& module) {
    for (const domain::ctr::CroSegment& segment : module.header.segments) {
        if (segment.type_known && segment.type == domain::ctr::CroSegmentType::Code &&
            segment.size != 0) {
            return &segment;
        }
    }
    return nullptr;
}

std::string
ModulesHeaderText(const std::vector<std::pair<std::string, std::vector<std::string>>>& modules) {
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#pragma once\n\n"
                       "#include \"domain/lift/runtime.h\"\n\n"
                       "namespace lifted_modules {\n\n"
                       "namespace runtime = hexlith::domain::lift::runtime;\n"
                       "namespace arm = hexlith::domain::arm;\n"
                       "namespace memory = hexlith::domain::memory;\n"
                       "namespace primitives = hexlith::domain::arm::primitives;\n\n";
    for (const auto& [name, declarations] : modules) {
        text += std::format("namespace {} {{\n\n", name);
        for (const std::string& declaration : declarations) {
            text += declaration;
            text += '\n';
        }
        text += std::format("\n}}  // namespace {}\n\n", name);
    }
    text += "}  // namespace lifted_modules\n";
    return text;
}

std::string ModulesRegistryText(const LiftModulesReport& report,
                                const std::vector<std::size_t>& shards_of) {
    const std::size_t count = report.modules.size();
    std::string text = "// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                       "#include \"modules.h\"\n\n"
                       "#include <deque>\n\n"
                       "namespace lifted_modules {\n";
    for (std::size_t module = 0; module < count; ++module) {
        const std::string& name = report.modules.at(module).name;
        text += std::format("namespace {} {{\n", name);
        for (std::size_t shard = 0; shard < shards_of.at(module); ++shard) {
            text += std::format("void {}(runtime::EntryTable& table);\n",
                                RegisterFunctionName(name, shard));
        }
        text += "}\n";
    }
    text += std::format(
        "\n}}  // namespace lifted_modules\n\n"
        "extern \"C\" {{\n\n"
        "__attribute__((visibility(\"default\"))) const char* {}() {{\n"
        "    return \"lifter={} modules={}\";\n"
        "}}\n\n"
        "// Calls offer with the name, the SHA-256 of the code the module was lifted from\n"
        "// and its table of entries for each module. The tables stay with the library.\n"
        "__attribute__((visibility(\"default\"))) void {}(\n"
        "    void (*offer)(void*, const char*, const char*, void*), void* context) {{\n"
        "    static std::deque<hexlith::domain::lift::runtime::EntryTable> tables;\n"
        "    if (tables.empty()) {{\n"
        "        tables.resize({});\n",
        ModulesManifestSymbol,
        LifterVersion,
        count,
        ModulesRegisterSymbol,
        count);
    for (std::size_t module = 0; module < count; ++module) {
        const std::string& name = report.modules.at(module).name;
        for (std::size_t shard = 0; shard < shards_of.at(module); ++shard) {
            text += std::format("        lifted_modules::{}::{}(tables[{}]);\n",
                                name,
                                RegisterFunctionName(name, shard),
                                module);
        }
    }
    text += "    }\n";
    for (std::size_t module = 0; module < count; ++module) {
        const ModuleReport& each = report.modules.at(module);
        text += std::format("    offer(context, \"{}\", \"{}\", &tables[{}]);\n",
                            each.name,
                            each.code_hash,
                            module);
    }
    text += "}\n\n}  // extern \"C\"\n";
    return text;
}

std::string ModulesManifestText(const LiftModulesReport& report) {
    std::string text = std::format("lifter={}\n", LifterVersion);
    for (const ModuleReport& each : report.modules) {
        text += std::format("{} code={} functions={}\n", each.name, each.code_hash, each.functions);
    }
    return text;
}

