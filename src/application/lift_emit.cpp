core::Result<LiftEmitReport> EmitLiftedCode(const LiftEmitRequest& request, ports::BlobSink& sink) {
    core::Result<LiftTables> tables = ReadLiftTables(request.functions, request.regions);
    if (!tables) {
        return tables.Failure();
    }
    std::vector<analysis::FunctionRange>& functions = tables.Value().functions;
    std::ranges::sort(
        functions, {}, [](const analysis::FunctionRange& function) { return function.address; });
    const std::unordered_set<std::uint32_t>& entries = tables.Value().entries;

    const lift::CodeImage image{.bytes = request.code, .base = request.base};
    const lift::FlowContext flow{.entries = &entries, .regions = tables.Value().regions};
    lift::EmitContext context;
    context.function_at =
        [&entries](std::uint32_t address,
                   domain::arm::InstructionSet set) -> std::optional<std::string> {
        if (entries.contains(address)) {
            return lift::DefaultFunctionName(address, set);
        }
        return std::nullopt;
    };

    LiftEmitReport report;
    report.code_hash = core::Sha256::Of(request.code).ToHex();
    report.functions = functions.size();

    std::vector<std::string> declarations;
    ShardWriter shards{sink, report, request.instructions_per_shard, MainLayout()};
    for (const analysis::FunctionRange& record : functions) {
        const lift::Function function =
            lift::BuildFunction(image, record.address, record.instruction_set, flow);
        const std::string name = lift::DefaultFunctionName(record.address, record.instruction_set);
        const lift::EmittedFunction emitted = lift::EmitFunction(function, name, context);

        declarations.push_back(lift::DeclarationOf(name));
        report.blocks += function.blocks.size();
        report.instructions += function.InstructionCount();
        const core::Status added = shards.Add(emitted.text,
                                              Registration(emitted, record.instruction_set, name),
                                              function.InstructionCount());
        if (!added) {
            return added.Failure();
        }
    }
    if (const core::Status closed = shards.Close(); !closed) {
        return closed.Failure();
    }
    report.shards = shards.Written();

    if (const core::Status written = WriteProjectFiles(declarations, report, sink); !written) {
        return written.Failure();
    }
    return report;
}

core::Result<LiftModulesReport> EmitLiftedModules(const LiftModulesRequest& request,
                                                  ports::BlobSink& sink) {
    std::set<std::string> names;
    for (const ModuleSource& source : request.modules) {
        if (!IsIdentifier(source.name)) {
            return core::Error{std::format("{} cannot name a namespace", source.name)};
        }
        if (!names.insert(source.name).second) {
            return core::Error{std::format("{} appears twice", source.name)};
        }
    }

    LiftModulesReport report;
    std::vector<std::pair<std::string, std::vector<std::string>>> declarations;
    std::vector<std::size_t> shards_of;
    std::vector<std::string> sources;
    for (const ModuleSource& source : request.modules) {
        core::Result<LiftedModule> lifted =
            LiftModule(source, request.instructions_per_shard, report.totals, sink);
        if (!lifted) {
            return lifted.Failure();
        }
        LiftedModule& module = lifted.Value();
        report.totals.functions += module.report.functions;
        report.totals.blocks += module.report.blocks;
        report.totals.instructions += module.report.instructions;
        report.totals.shards += module.shards;
        for (std::size_t shard = 0; shard < module.shards; ++shard) {
            sources.push_back(ShardName(source.name, shard));
        }
        declarations.emplace_back(source.name, std::move(module.declarations));
        shards_of.push_back(module.shards);
        report.modules.push_back(std::move(module.report));
    }

    const std::string header = ModulesHeaderText(declarations);
    const std::string registry = ModulesRegistryText(report, shards_of);
    const std::string manifest = ModulesManifestText(report);
    const std::string cmake = ModulesCMakeText(sources);
    for (const auto& [path, text] :
         {std::pair<std::string_view, const std::string&>{ModulesHeader, header},
          {"registry.cpp", registry},
          {ModulesManifestFile, manifest},
          {"CMakeLists.txt", cmake}}) {
        if (const core::Status written = sink.WriteText(path, text); !written) {
            return written.Failure();
        }
        CountWritten(report.totals, text);
    }
    return report;
}

std::string RenderLiftModulesSummary(const LiftModulesReport& report) {
    std::size_t relocated = 0;
    for (const ModuleReport& each : report.modules) {
        relocated += each.relocated_words;
    }
    return std::format(
        "{} module(s), {} function(s) in {} shard(s), {} block(s), {} instruction(s)\n"
        "{} line(s) of C++, {} byte(s)\n"
        "{} relocated word(s) of code left to the interpreter\n",
        report.modules.size(),
        report.totals.functions,
        report.totals.shards,
        report.totals.blocks,
        report.totals.instructions,
        report.totals.source_lines,
        report.totals.source_bytes,
        relocated);
}

std::filesystem::path ModulesLibraryBeside(const std::filesystem::path& lifted_library) {
    return (lifted_library.parent_path() / ".." / "modules" / "build" / "libhexlith_modules.so")
        .lexically_normal();
}

std::string RenderLiftEmitSummary(const LiftEmitReport& report) {
    return std::format("{} function(s) in {} shard(s), {} block(s), {} instruction(s)\n"
                       "{} line(s) of C++, {} byte(s)\n"
                       "lifted from code {}\n",
                       report.functions,
                       report.shards,
                       report.blocks,
                       report.instructions,
                       report.source_lines,
                       report.source_bytes,
                       report.code_hash);
}

