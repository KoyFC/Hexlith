core::Result<LiftEmitReport> EmitLiftedCode(const LiftEmitRequest& request, ports::BlobSink& sink) {
    core::Result<std::vector<analysis::FunctionRange>> functions =
        analysis::ParseFunctions(request.functions);
    if (!functions) {
        return functions.Failure().WithContext("functions.txt");
    }
    core::Result<std::vector<analysis::Region>> regions = analysis::ParseRegions(request.regions);
    if (!regions) {
        return regions.Failure().WithContext("regions.txt");
    }
    std::ranges::sort(
        regions.Value(), {}, [](const analysis::Region& region) { return region.address; });
    std::ranges::sort(functions.Value(), {}, [](const analysis::FunctionRange& function) {
        return function.address;
    });

    std::unordered_set<std::uint32_t> entries;
    for (const analysis::FunctionRange& function : functions.Value()) {
        entries.insert(function.address);
    }

    const lift::CodeImage image{.bytes = request.code, .base = request.base};
    const lift::FlowContext flow{.entries = &entries, .regions = regions.Value()};
    lift::EmitContext context;
    context.function_at =
        [&entries](std::uint32_t address,
                   domain::arm::InstructionSet set) -> std::optional<std::string> {
        if (entries.contains(address)) {
            return lift::DefaultFunctionName(address, set);
        }
        return std::nullopt;
    };

    LiftEmitReport report;
    report.code_hash = core::Sha256::Of(request.code).ToHex();
    report.functions = functions.Value().size();

    std::vector<std::string> declarations;
    std::string shard_text;
    std::string registration;
    std::size_t shard_instructions = 0;
    std::size_t shard_index = 0;

    const auto close_shard = [&]() -> core::Status {
        if (shard_text.empty()) {
            return {};
        }
        const std::string text =
            std::format("// Generated by hexlith-lift. Derived from the game; never checked in.\n"
                        "#include \"{}\"\n\nnamespace lifted {{\n\n{}\n"
                        "void {}(runtime::EntryTable& table) {{\n{}}}\n\n}}  // namespace lifted\n",
                        Header,
                        shard_text,
                        RegisterFunctionName(shard_index),
                        registration);
        report.source_bytes += text.size();
        report.source_lines += static_cast<std::size_t>(std::ranges::count(text, '\n'));
        const core::Status written = sink.WriteText(ShardName(shard_index), text);
        shard_text.clear();
        registration.clear();
        shard_instructions = 0;
        ++shard_index;
        return written;
    };

    for (const analysis::FunctionRange& record : functions.Value()) {
        const lift::Function function =
            lift::BuildFunction(image, record.address, record.instruction_set, flow);
        const std::string name = lift::DefaultFunctionName(record.address, record.instruction_set);
        const lift::EmittedFunction emitted = lift::EmitFunction(function, name, context);

        declarations.push_back(lift::DeclarationOf(name));
        shard_text += emitted.text;
        shard_text += '\n';
        for (const std::uint32_t entry : emitted.entries) {
            registration += std::format(
                "    table.Add(0x{:08X}U, {}, &{});\n",
                entry,
                record.instruction_set == domain::arm::InstructionSet::Thumb ? "true" : "false",
                name);
        }
        report.blocks += function.blocks.size();
        report.instructions += function.InstructionCount();
        shard_instructions += function.InstructionCount();

        if (shard_instructions >= request.instructions_per_shard) {
            if (const core::Status closed = close_shard(); !closed) {
                return closed.Failure();
            }
        }
    }
    if (const core::Status closed = close_shard(); !closed) {
        return closed.Failure();
    }
    report.shards = shard_index;

    const std::string header = HeaderText(declarations);
    const std::string registry = RegistryText(report.shards, report);
    const std::string cmake = CMakeText(report.shards);
    for (const auto& [path, text] :
         {std::pair<std::string_view, const std::string&>{Header, header},
          {"registry.cpp", registry},
          {"CMakeLists.txt", cmake}}) {
        if (const core::Status written = sink.WriteText(path, text); !written) {
            return written.Failure();
        }
        report.source_bytes += text.size();
        report.source_lines += static_cast<std::size_t>(std::ranges::count(text, '\n'));
    }
    return report;
}

std::string RenderLiftEmitSummary(const LiftEmitReport& report) {
    return std::format("{} function(s) in {} shard(s), {} block(s), {} instruction(s)\n"
                       "{} line(s) of C++, {} byte(s)\n"
                       "lifted from code {}\n",
                       report.functions,
                       report.shards,
                       report.blocks,
                       report.instructions,
                       report.source_lines,
                       report.source_bytes,
                       report.code_hash);
}

