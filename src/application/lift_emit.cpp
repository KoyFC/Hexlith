struct LiftedModule {
    ModuleReport report;
    std::vector<std::string> declarations;
    std::size_t shards = 0;
};

core::Result<LiftedModule> LiftModule(const ModuleSource& source,
                                      std::size_t instructions_per_shard,
                                      LiftEmitReport& totals,
                                      ports::BlobSink& sink) {
    const core::Result<domain::linker::CroModule> read = domain::linker::ReadCroModule(source.file);
    if (!read) {
        return core::Error{
            std::format("{} is not a module: {}", source.name, read.Failure().Message())};
    }
    const domain::linker::CroModule& module = read.Value();
    const domain::ctr::CroSegment* code = CodeSegmentOf(module);
    if (code == nullptr || code->offset + code->size > source.file.size()) {
        return core::Error{std::format("{} has no code segment inside its file", source.name)};
    }
    core::Result<LiftTables> tables = ReadLiftTables(source.functions, source.regions);
    if (!tables) {
        return core::Error{std::format("{}: {}", source.name, tables.Failure().Message())};
    }
    std::vector<analysis::FunctionRange>& functions = tables.Value().functions;
    std::ranges::sort(
        functions, {}, [](const analysis::FunctionRange& function) { return function.address; });
    const std::unordered_set<std::uint32_t>& entries = tables.Value().entries;
    const std::unordered_set<std::uint32_t> relocated = RelocatedCodeWords(module);

    // The module is read as if it were mapped at zero: an address is an offset
    // into the file.
    const lift::CodeImage image{.bytes = source.file, .base = 0};
    const lift::FlowContext flow{.entries = &entries, .regions = tables.Value().regions};
    lift::EmitContext context;
    context.module = true;
    context.function_at =
        [&entries](std::uint32_t address,
                   domain::arm::InstructionSet set) -> std::optional<std::string> {
        if (entries.contains(address)) {
            return lift::DefaultFunctionName(address, set);
        }
        return std::nullopt;
    };
    context.relocated = [&relocated](std::uint32_t address) { return relocated.contains(address); };

    LiftedModule lifted;
    lifted.report.name = source.name;
    lifted.report.code_hash =
        core::Sha256::Of(source.file.subspan(code->offset, code->size)).ToHex();
    lifted.report.functions = functions.size();
    lifted.report.relocated_words = relocated.size();

    ShardWriter shards{sink, totals, instructions_per_shard, ModuleLayout(source.name)};
    for (const analysis::FunctionRange& record : functions) {
        const lift::Function function =
            lift::BuildFunction(image, record.address, record.instruction_set, flow);
        const std::string name = lift::DefaultFunctionName(record.address, record.instruction_set);
        const lift::EmittedFunction emitted = lift::EmitFunction(function, name, context);

        lifted.declarations.push_back(lift::DeclarationOf(name));
        lifted.report.blocks += function.blocks.size();
        lifted.report.instructions += function.InstructionCount();
        const core::Status added = shards.Add(emitted.text,
                                              Registration(emitted, record.instruction_set, name),
                                              function.InstructionCount());
        if (!added) {
            return added.Failure();
        }
    }
    if (const core::Status closed = shards.Close(); !closed) {
        return closed.Failure();
    }
    lifted.shards = shards.Written();
    return lifted;
}

