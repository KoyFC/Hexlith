#include "domain/video/morton.h"

#include <array>
#include <cstdint>
#include <gtest/gtest.h>

namespace hexlith::domain::video {
namespace {

// The single tile of GBATEK's example in 3DS Video Texture Swizzling: the
// pixel of the linear 8x8 bitmap stored at each position of the tile.
constexpr std::array<std::uint32_t, TilePixels> SwizzledTile = {
    0x00, 0x01, 0x08, 0x09, 0x02, 0x03, 0x0A, 0x0B, 0x10, 0x11, 0x18, 0x19, 0x12, 0x13, 0x1A, 0x1B,
    0x04, 0x05, 0x0C, 0x0D, 0x06, 0x07, 0x0E, 0x0F, 0x14, 0x15, 0x1C, 0x1D, 0x16, 0x17, 0x1E, 0x1F,
    0x20, 0x21, 0x28, 0x29, 0x22, 0x23, 0x2A, 0x2B, 0x30, 0x31, 0x38, 0x39, 0x32, 0x33, 0x3A, 0x3B,
    0x24, 0x25, 0x2C, 0x2D, 0x26, 0x27, 0x2E, 0x2F, 0x34, 0x35, 0x3C, 0x3D, 0x36, 0x37, 0x3E, 0x3F,
};

TEST(MortonIndex, StoresATileAsGbatekShowsIt) {
    for (std::uint32_t y = 0; y < TileSide; ++y) {
        for (std::uint32_t x = 0; x < TileSide; ++x) {
            EXPECT_EQ(SwizzledTile.at(MortonIndex(x, y)), (y * TileSide) + x) << x << ", " << y;
        }
    }
}

}  // namespace
}  // namespace hexlith::domain::video
